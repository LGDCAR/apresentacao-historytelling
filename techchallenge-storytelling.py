"""O gráfico mostrando os Top 10 Estados com Mais Clientes foi gerado e exibido com sucesso. Você pode ver a distribuição geográfica dos seus clientes."""

# Faturamento Mensal

df_vendas = pd.merge(orderes, payments, on='order_id')
df_vendas['order_purchase_timestamp'] = pd.to_datetime(df_vendas['order_purchase_timestamp'])
df_vendas['mes_ano'] = df_vendas['order_purchase_timestamp'].dt.to_period('M')
receita_mensal = df_vendas.groupby('mes_ano')['payment_value'].sum()

plt.figure(figsize=(12, 6))
